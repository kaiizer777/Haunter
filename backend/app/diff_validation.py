"""Strict, pure validation of model-authored unified diffs.

Remediation patches are generated by an LLM and may be applied to a user's
branch without human review. The applier in :mod:`app.github.pr` walks hunk
bodies and silently tolerates trailing content, so syntax alone is not a
sufficient gate: a patch is only trusted when every declared hunk count is
met exactly, every file header is well-formed and repository-relative, and no
patch-envelope or "no remediation" sentinel leaked into the text.

This module is deliberately dependency-free so the webhook selection path, the
auditor renderer, the PR writer and the commit choke point can all share one
definition of "valid diff".
"""

from __future__ import annotations

import re
from typing import Optional

# A hunk header line number past this bound cannot describe a real file and is
# treated as malformed rather than handed to the tree API.
MAX_DIFF_LINE_NUMBER = 10_000_000

# A single hunk is allowed to carry at most this many lines on either side.
MAX_DIFF_HUNK_LINES = 100_000

_NO_REMEDIATION_SENTINEL = "(no automated remediation"
_NO_NEWLINE_MARKER = "\\ No newline at end of file"
_DEV_NULL = "/dev/null"

_HUNK_RE = re.compile(r"^@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@")

_ENVELOPE_RE = re.compile(
    r"^\*\*\* (?:Begin Patch|End Patch|Update File|Add File|Delete File|Move to)\b"
)

# Metadata emitted by `git diff` before a file's ---/+++ headers. Accepted so a
# genuine git patch is not rejected for carrying them; none of these lines can
# describe content, and rename/copy directives are intentionally absent because
# the applier cannot perform them.
_DIFF_METADATA_PREFIXES = (
    "index ",
    "new file mode ",
    "deleted file mode ",
    "old mode ",
    "new mode ",
)


class InvalidUnifiedDiffError(ValueError):
    """Raised when text is not a strictly valid, safe unified diff."""


def _fail(reason: str) -> None:
    raise InvalidUnifiedDiffError(reason)


def _validate_repo_path(path: str) -> None:
    """Reject paths the Git Data API must never receive from a model patch."""
    if not path or len(path) > 1024:
        _fail("file header contains an invalid path")
    if path.startswith("/") or "\\" in path or "\x00" in path:
        _fail("file header contains an absolute or non-portable path")
    if any(ord(character) < 32 or ord(character) == 127 for character in path):
        _fail("file header contains control characters")

    parts = path.split("/")
    if any(part in ("", ".", "..") for part in parts):
        _fail("file header contains path traversal")

    folded = [part.casefold() for part in parts]
    if any(part == ".git" for part in folded):
        _fail("file header targets git metadata")
    if folded[0] == ".github" and len(folded) > 1 and folded[1] == "workflows":
        _fail("file header targets GitHub workflow definitions")


def _parse_header_path(line: str, marker: str) -> tuple[bool, str]:
    """Parse a ``---``/``+++`` line into (is_dev_null, repository path)."""
    raw = line[len(marker) :].strip()
    # `git diff` appends a timestamp after a tab; the applier strips it too.
    path = raw.split("\t", 1)[0].strip()
    if not path:
        _fail(f"'{marker.strip()}' header has no path")
    if path == _DEV_NULL:
        return True, path
    if path.startswith('"') or path.endswith('"'):
        _fail("file header contains a quoted path")
    if path.startswith("a/") or path.startswith("b/"):
        path = path[2:]
    _validate_repo_path(path)
    return False, path


def _parse_hunk_header(line: str) -> tuple[int, int]:
    match = _HUNK_RE.match(line)
    if match is None:
        _fail("malformed hunk header")
    old_start = int(match.group(1))
    new_start = int(match.group(3))
    old_count = 1 if match.group(2) is None else int(match.group(2))
    new_count = 1 if match.group(4) is None else int(match.group(4))
    if (
        old_start > MAX_DIFF_LINE_NUMBER
        or new_start > MAX_DIFF_LINE_NUMBER
        or old_count > MAX_DIFF_HUNK_LINES
        or new_count > MAX_DIFF_HUNK_LINES
    ):
        _fail("hunk header declares an out-of-range line or count")
    return old_count, new_count


def validate_unified_diff(patch_text: str) -> None:
    """Validate ``patch_text`` as a strictly well-formed unified diff.

    Raises:
        InvalidUnifiedDiffError: if the patch is empty, contains an
            unsupported envelope/sentinel, has unsafe paths, or contains a
            hunk whose body does not exactly match its declared counts.
    """
    if not isinstance(patch_text, str) or not patch_text.strip():
        _fail("patch is empty")
    if _NO_REMEDIATION_SENTINEL in patch_text.casefold():
        _fail("patch contains the no-remediation sentinel")

    lines = patch_text.splitlines()
    pending_old: Optional[tuple[bool, str]] = None
    in_file = False
    file_hunks = 0
    saw_hunk = False
    # [old lines still expected, new lines still expected]
    hunk: Optional[list[int]] = None

    for index, raw_line in enumerate(lines, start=1):
        line = raw_line.replace("\r", "")

        if _ENVELOPE_RE.match(line):
            _fail(f"line {index}: patch-envelope markers are not a unified diff")

        if line == _NO_NEWLINE_MARKER:
            if pending_old is not None or not in_file:
                _fail(f"line {index}: no-newline marker outside a file section")
            continue

        if hunk is not None and hunk[0] == 0 and hunk[1] == 0:
            # The hunk fulfilled its header; the next record belongs to the
            # file section or starts a new hunk.
            hunk = None

        if hunk is not None:
            if line.startswith("@@"):
                _fail(f"line {index}: hunk ended before its declared counts were met")
            if line.startswith(("--- ", "+++ ", "diff --git ")):
                _fail(f"line {index}: file header appeared inside an open hunk")
            if line.startswith(" ") or line == "":
                # An empty line inside a hunk is an empty *context* line:
                # `git apply`, app.sandbox.mirror.apply_unified_diff and
                # app.github.pr._apply_unified_diff_to_content all count it
                # as one old + one new line.
                if hunk[0] <= 0 or hunk[1] <= 0:
                    _fail(f"line {index}: hunk body exceeds its declared counts")
                hunk[0] -= 1
                hunk[1] -= 1
                continue
            if line.startswith("-"):
                if hunk[0] <= 0:
                    _fail(f"line {index}: hunk body exceeds its declared counts")
                hunk[0] -= 1
                continue
            if line.startswith("+"):
                if hunk[1] <= 0:
                    _fail(f"line {index}: hunk body exceeds its declared counts")
                hunk[1] -= 1
                continue
            _fail(f"line {index}: invalid hunk body line")

        if line == "":
            continue

        if line.startswith("diff --git "):
            if pending_old is not None:
                _fail(f"line {index}: new file header before '---'/'+++' pair")
            if in_file:
                if file_hunks == 0:
                    _fail(f"line {index}: file header has no hunks")
                in_file = False
                file_hunks = 0
            continue

        if line.startswith("--- "):
            if pending_old is not None:
                _fail(f"line {index}: duplicate '---' header")
            if in_file:
                if file_hunks == 0:
                    _fail(f"line {index}: file header has no hunks")
                in_file = False
                file_hunks = 0
            pending_old = _parse_header_path(line, "--- ")
            continue

        if line.startswith("+++ "):
            if pending_old is None:
                _fail(f"line {index}: '+++' header without a preceding '---' header")
            old_dev_null, _ = pending_old
            new_dev_null, _ = _parse_header_path(line, "+++ ")
            if old_dev_null and new_dev_null:
                _fail(f"line {index}: file has no old or new path")
            pending_old = None
            in_file = True
            file_hunks = 0
            continue

        if line.startswith("@@"):
            if pending_old is not None:
                _fail(f"line {index}: hunk appears before the '+++' header")
            if not in_file:
                _fail(f"line {index}: hunk appears outside a file section")
            old_count, new_count = _parse_hunk_header(line)
            hunk = [old_count, new_count]
            file_hunks += 1
            saw_hunk = True
            continue

        if line.startswith(_DIFF_METADATA_PREFIXES):
            continue

        _fail(f"line {index}: unexpected content outside a hunk")

    if pending_old is not None:
        _fail("'---' header has no matching '+++' header")
    if hunk is not None and (hunk[0] or hunk[1]):
        _fail("truncated hunk: declared line counts were not met")
    if in_file and file_hunks == 0:
        _fail("file header has no hunks")
    if not saw_hunk:
        _fail("patch contains no hunks")


def is_valid_unified_diff(patch_text: str) -> bool:
    """Return True when :func:`validate_unified_diff` accepts ``patch_text``."""
    try:
        validate_unified_diff(patch_text)
    except InvalidUnifiedDiffError:
        return False
    return True


def _strip_outer_fence(text: str) -> Optional[str]:
    lines = text.splitlines()
    if (
        len(lines) >= 3
        and lines[0].startswith("```")
        and lines[-1].strip() == "```"
    ):
        return "\n".join(lines[1:-1]).strip("\r\n")
    return None


def coerce_unified_diff(
    text: str,
    *,
    file_path: Optional[str] = None,
) -> Optional[str]:
    """Return a validated diff from model text, or None when none is valid.

    A single outer Markdown fence is unwrapped (models habitually emit one),
    and a bare hunk is completed with ``--- a/<path>`` / ``+++ b/<path>`` only
    when a repository path is available. No hunk body is ever synthesized or
    rewritten; the candidate must already satisfy the strict validator.
    """
    if not isinstance(text, str):
        return None
    candidate = text.strip("\r\n")
    if not candidate.strip():
        return None

    candidates: list[str] = []
    fenced = _strip_outer_fence(candidate)
    if fenced:
        candidates.append(fenced)
    candidates.append(candidate)

    if file_path:
        bare = fenced if fenced and fenced.lstrip().startswith("@@") else None
        if bare is None and candidate.lstrip().startswith("@@"):
            bare = candidate
        if bare is not None:
            candidates.append(
                f"--- a/{file_path}\n+++ b/{file_path}\n{bare.strip()}"
            )

    for attempt in candidates:
        if not attempt.strip():
            continue
        try:
            validate_unified_diff(attempt)
        except InvalidUnifiedDiffError:
            continue
        normalized = attempt.strip("\r\n")
        return normalized + "\n"
    return None
